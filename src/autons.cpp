    chassis.turnToHeading(0, 1000);
    chassis.waitUntilDone();
    pros::delay(100);
    chassis.setPose(67.5 - right.get_distance() / 25.4, fmax(back_right.get_distance(),back_left.get_distance()) / 25.4 - 67, 0);
    chassis.moveToPoint(24, -48, 1000, {.forwards = false, .maxSpeed = 60, .minSpeed = 40, .earlyExitRange = 12});
    cintake(0);
    chassis.waitUntilDone();
    chassis.arcade(-40, 0);
    pros::delay(500);
    voltage = -80;
    cintake(-20);
    wait_until_claw(1000);
    voltage = 0;
    pros::delay(200);
    voltage = -80;
    chassis.arcade(60, 0);
    pros::delay(300);


