void basic_auton(){
    chassis.setPose(0,0,0);
    chassis.moveToPoint(0, -24, 1000, {.forwards = false, .minSpeed = 10, .earlyExitRange = 10});
    chassis.waitUntilDone();
    chassis.turnToPoint(24,-24, 1000, {.minSpeed = 20, .earlyExitRange = 5});
    chassis.waitUntilDone();
    chassis.moveToPoint(24, -24, 1000, {.minSpeed = 10, .earlyExitRange = 8});
    chassis.waitUntilDone();
    chassis.turnToPoint(24, 0, 1000, {.minSpeed = 20, .earlyExitRange = 5});
    chassis.waitUntilDone();
    chassis.moveToPoint(24, 0, 1000);
    chassis.waitUntilDone();
    chassis.turnToPoint(48, 0, 1000);
    chassis.waitUntilDone();
    chassis.moveToPoint(48, 0, 1000);
    chassis.waitUntilDone();
    chassis.moveToPoint(0,0, 1000, {.forwards = false});
    chassis.waitUntilDone();
    chassis.turnToHeading(0, 1000);
    chassis.waitUntilDone();
}

