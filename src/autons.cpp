    pros::delay(500);
    chassis.arcade(127, 0);
    pros::delay(500);
    voltage = -127;
    pros::delay(500);
    chassis.arcade(-60, 0);
    pros::delay(600);
    chassis.turnToHeading(0, 1000);
    chassis.waitUntilDone();
    chassis.setPose(left.get_distance() / 25.4 - 67.5, fmax(back_right.get_distance(), back_left.get_distance()) / 25.4 - 67, 0);
    chassis.turnToPoint(-24, -24, 1000, {.minSpeed = 20, .earlyExitRange = 5});
